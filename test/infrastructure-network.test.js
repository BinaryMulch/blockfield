async function connect(game, token = randomUUID()) {
  const socket = new WebSocket(`ws://127.0.0.1:${game.server.address().port}/multiplayer`), messages = [], waiting = new Set();
  socket.on('message', raw => { messages.push(JSON.parse(raw)); for (const fn of waiting) fn(); });
  const next = predicate => new Promise((resolve, reject) => {
    const timer = setTimeout(() => { waiting.delete(check); reject(new Error('Timed out waiting for storage response')); }, 5000);
    function check() { const i = messages.findIndex(predicate); if (i >= 0) { clearTimeout(timer); waiting.delete(check); resolve(messages.splice(i, 1)[0]); } }
    waiting.add(check); check();
  });
  let requestId = 0;
  const request = (method, args = {}) => { const id = ++requestId; socket.send(JSON.stringify({ type: 'command', method, requestId: id, ...args })); return next(m => m.type === 'result' && m.requestId === id); };
  socket.on('open', () => socket.send(JSON.stringify({ type: 'hello', protocol: PROTOCOL, name: 'Outpost builder', playerToken: token })));
  return { socket, next, request, welcome: await next(m => m.type === 'welcome') };
}

test('shared cabinet races checkpoint once, broadcast to peers, and survive host restart with construction damage', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'blockfield-storage-')), sockets = [];
  let game = await createGameServer({ host: '127.0.0.1', port: 0, saveDirectory: directory });
  t.after(async () => { sockets.forEach(s => s.terminate()); await game.close(); await rm(directory, { recursive: true, force: true }); });
  const a = await connect(game), b = await connect(game); sockets.push(a.socket, b.socket);
  const { x, y, z } = game.room.horror.cabin, p = { x: x + 4, y: y + 1, z: z + 1 };
  for (const c of [a, b]) Object.assign(game.room.players.get(c.welcome.self.id).pose, { x: x + 4.5, y: y + 1, z: z + 3.5 });
  const owner = game.room.players.get(a.welcome.self.id); owner.pose.yaw = Math.PI / 2;
  owner.inventory.stacks[0] = { block: STORAGE_CABINET, count: 1 }; owner.inventory.stacks[1] = { block: WOOD, count: 23 };
  assert.equal((await a.request('edit', { ...p, block: STORAGE_CABINET, slot: 0, expected: game.room.expected(p.x, p.y, p.z) })).ok, true);
  assert.equal(game.room.world.get(p.x, p.y, p.z), cabinetBlock(3));
  const placed = await b.next(m => m.type === 'edit');
  assert.ok(placed.updates.some(update => update.changes.some(c => c.x === p.x && c.y === p.y && c.z === p.z && c.to === cabinetBlock(3))));
  const opened = await a.request('openStorage', p); assert.equal(opened.ok, true);
  const deposit = await a.request('storage', { ...p, containerId: opened.storage.id, revision: 0, source: 'player', index: 1, amount: 23, expectedSource: { block: WOOD, count: 23 } });
  assert.equal(deposit.ok, true); assert.equal(deposit.moved, 23);
  assert.equal((await b.next(m => m.type === 'storage' && m.storage.revision === 1)).storage.stacks[0].count, 23);
  let disk = JSON.parse(await readFile(join(directory, 'world.json'), 'utf8'));
  assert.equal(disk.containers[0].stacks[0].count, 23); assert.equal(disk.profiles.find(([token]) => token === owner.token)[1].stacks[1], null);
  const shared = (await b.request('openStorage', p)).storage;
  const args = { ...p, containerId: shared.id, revision: shared.revision, source: 'storage', index: 0, amount: 23, expectedSource: { block: WOOD, count: 23 } };
  const results = await Promise.all([a.request('storage', args), b.request('storage', args)]);
  assert.equal(results.filter(r => r.ok).length, 1); assert.equal(results.find(r => !r.ok).reason, 'changed');
  assert.deepEqual(results[0].storage, results[1].storage);
  assert.equal([...game.room.profiles.values()].reduce((n, inventory) => n + inventory.count(WOOD), 0), 23);
  const winner = results[0].ok ? a : b, current = results.find(r => r.ok).storage;
  assert.equal((await winner.request('storage', { ...p, containerId: current.id, revision: current.revision, source: 'player', index: 0, amount: 23, expectedSource: { block: WOOD, count: 23 } })).ok, true);
  const panel = { x: x + 6, y: y + 1, z: z + 2 };
  const hit = await a.request('edit', { ...panel, block: AIR, expected: game.room.expected(panel.x, panel.y, panel.z) });
  assert.equal(hit.remaining, 3);
  assert.equal((await b.next(m => m.type === 'construction')).damage.remaining, 3);
  disk = JSON.parse(await readFile(join(directory, 'world.json'), 'utf8'));
  assert.equal(disk.construction[0].remaining, 3); assert.equal(disk.containers[0].stacks[0].count, 23);
  await game.close();
  game = await createGameServer({ host: '127.0.0.1', port: 0, saveDirectory: directory });
  assert.equal(game.room.infrastructure.snapshot().containers[0].stacks[0].count, 23);
  assert.equal(game.room.infrastructure.snapshot().construction[0].remaining, 3);
  assert.equal(game.room.world.get(panel.x, panel.y, panel.z), REINFORCED_PANEL);
  assert.equal(game.room.world.get(p.x, p.y, p.z), cabinetBlock(3));
  const returning = await connect(game, owner.token); sockets.push(returning.socket);
  Object.assign(game.room.players.get(returning.welcome.self.id).pose, { x: x + 4.5, y: y + 1, z: z + 3.5 });
  assert.deepEqual((await returning.request('openStorage', p)).storage, disk.containers[0]);
  const streamed = await returning.next(m => m.type === 'chunk' && m.cx === Math.floor(panel.x / 16) && m.cz === Math.floor(panel.z / 16));
  assert.deepEqual(streamed.construction, disk.construction, 'damage is present in the first chunk snapshot after rejoining');
  const player = game.room.players.get(returning.welcome.self.id);
  player.inventory.stacks[0] = { block: REPAIR_TOOL, count: 1 }; player.inventory.stacks[1] = { block: PLANKS, count: 1 };
  assert.equal((await returning.request('repair', panel)).ok, true);
  assert.equal((await returning.next(m => m.type === 'construction')).damage.remaining, 4);
  assert.deepEqual(game.room.chunkSnapshot(Math.floor(panel.x / 16), Math.floor(panel.z / 16)).construction, []);
  assert.deepEqual(JSON.parse(await readFile(join(directory, 'world.json'), 'utf8')).construction, []);
});

test('private storage and damage persist, and failed saves retain both sides for retry/export', async t => {
  const previous = globalThis.Worker;
  globalThis.Worker = class { postMessage(job) { queueMicrotask(() => this.onmessage?.({ data: { id: job.id, blocks: generateChunk(job.seed, job.cx, job.cz, job.size) } })); } terminate() {} };
  t.after(() => { if (previous) globalThis.Worker = previous; else delete globalThis.Worker; });
  let fail = false;
  t.mock.method(browserSaves, 'save', async (value, revision) => {
    if (fail) throw new Error('Disk unavailable');
    return structuredClone({ ...value, saveRevision: revision + 1 });
  });
  const local = new LocalSession(new ChunkWorld({ generate: false })); t.after(() => local.disconnect());
  await local.start('Builder', 'Woodland cabin', 'private-storage');
  const { x, y, z } = local.horror.cabin, p = { x: x + 4, y: y + 1, z: z + 1 };
  local.pose = () => ({ ...local.self, x: x + 4.5, y: y + 1, z: z + 3.5, yaw: Math.PI / 2 });
  local.resources.stacks[0] = { block: STORAGE_CABINET, count: 1 }; local.resources.stacks[1] = { block: WOOD, count: 14 };
  assert.equal((await local.request('edit', { ...p, block: STORAGE_CABINET, slot: 0 })).ok, true);
  assert.equal(local.world.get(p.x, p.y, p.z), cabinetBlock(3));
  const opened = await local.request('openStorage', p);
  fail = true;
  const result = await local.request('storage', { ...p, containerId: opened.storage.id, revision: 0, source: 'player', index: 1, amount: 14, expectedSource: { block: WOOD, count: 14 } });
  assert.equal(result.reason, 'storage'); assert.equal(local.resources.count(WOOD), 0);
  assert.equal(local.snapshot().containers[0].stacks[0].count, 14);
  assert.equal((await local.request('craft', { block: REINFORCED_PANEL })).reason, 'storage');
  fail = false; assert.equal((await local.request('save')).ok, true);
  assert.equal((await local.request('edit', { x: x + 6, y: y + 1, z: z + 2, block: AIR })).remaining, 3);
  const saved = local.snapshot(), resumed = new LocalSession(new ChunkWorld({ generate: false })); t.after(() => resumed.disconnect());
  const visualDamage = new DamageState(resumed.world);
  resumed.callbacks.constructionChunk = ({ key, damage }) => visualDamage.setChunk(key, damage);
  resumed.callbacks.construction = damage => visualDamage.set(damage);
  await resumed.start('Builder', '', '', JSON.parse(JSON.stringify(saved)));
  assert.deepEqual(resumed.infrastructure.snapshot(), local.infrastructure.snapshot());
  const cx = Math.floor(p.x / 16), cz = Math.floor(p.z / 16);
  await resumed.generate(cx, cz);
  assert.equal(resumed.world.get(p.x, p.y, p.z), cabinetBlock(3));
  assert.equal(resumed.resources.count(WOOD), 0); assert.equal(resumed.infrastructure.snapshot().containers[0].stacks[0].count, 14);
  const panel = { x: x + 6, y: y + 1, z: z + 2 };
  assert.equal(visualDamage.remaining(panel.x, panel.y, panel.z, REINFORCED_PANEL), 3);
  resumed.pose = local.pose; resumed.resources.stacks[0] = { block: REPAIR_TOOL, count: 1 }; resumed.resources.stacks[1] = { block: PLANKS, count: 1 };
  assert.equal((await resumed.request('repair', panel)).ok, true);
  assert.equal(visualDamage.remaining(panel.x, panel.y, panel.z, REINFORCED_PANEL), 4);
  assert.deepEqual(resumed.infrastructure.chunkDamage(cx, cz), []);
});
